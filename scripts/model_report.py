"""decisions and why of scripts/model: the generated index of spec/decisions/, and a requirement's trace to its
initiative's sources."""

import json
import os
from pathlib import Path

from model_facts import Model
from model_parse import DECISIONS, as_list, decision_files, expand, frontmatter


def render_decisions(root):
    index = Model(root)
    index.read_index()
    rows = []
    for path in decision_files(root):
        data, _ = frontmatter(path.read_text())
        if not data.get("id"):
            continue
        rows.append((path.name, data))
    lines = ["# Decisions", "",
             "Generated by `scripts/model decisions` from `spec/decisions/`; never edited by hand.",
             "Each decision's `## Decision` section is standing; the rest of its file is record.", "",
             "| decision | summary | status | supersedes | revisit when |",
             "|---|---|---|---|---|"]
    for name, d in rows:
        sup = ", ".join(index.qualify(s, "design-decision") for s in as_list(d.get("supersedes"))) or ""
        rev = d.get("revisit_when") or ""
        cell = lambda s: str(s).replace("|", "\\|")
        lines.append(f"| [{d['id']}]({name}) | {cell(d.get('summary', ''))} | "
                     f"{d.get('status', '')} | {cell(sup)} | {cell(rev)} |")
    return "\n".join(lines) + "\n"


def cmd_decisions(args):
    text = render_decisions(args.root)
    target = Path(args.root) / DECISIONS / "index.md"
    if args.check:
        current = target.read_text() if target.exists() else ""
        if current != text:
            print("spec/decisions/index.md is not what `model decisions` writes: run it")
            return 1
        print("spec/decisions/index.md is current")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    print(f"wrote {target.relative_to(args.root) if not os.path.isabs(args.root) else target}")
    return 0


def cmd_why(args):
    model = Model(args.root).read()
    q = model.resolve_req(args.ref, "why")
    if not q:
        print("\n".join(model.dangling))
        return 2
    text = model.req_text.get(q)
    traced = []
    for p, data in sorted(model.proposals.items(), key=lambda t: str(t[1].get("date", ""))):
        rels = [rel for rel in ("adds", "changes", "removes")
                if q in [model.resolve_req(r, p) for r in expand(as_list(data.get(rel)))]]
        if rels:
            traced.append((p, data, rels))
    if getattr(args, "json", False):
        print(json.dumps({"requirement": q, "text": text, "proposals": [
            {"id": p, "relation": rels, "status": data.get("status"), "date": str(data["date"]) if data.get("date") else None}
            for p, data, rels in traced]}, indent=1))
        return 0
    print(f"{q}: {text}" if text is not None else f"{q}: no capability has this requirement now")
    found = False
    for p, data, rels in traced:
        found = found or bool(set(rels) & {"adds", "changes"})
        print(f"  {'/'.join(rels)} by capability-proposal {p} ({data.get('status')}, {data.get('date', 'undated')})")
        chain, cur, seen = [], model.parents.get(p), set()
        while cur and cur not in seen:
            seen.add(cur)
            chain.append(cur)
            cur = model.parents.get(cur)
        for c in chain:
            kind = model.nodes.get(c, "?")
            print(f"    part_of {kind} {c}")
            if kind == "initiative":
                for s in model.sources.get(c, []):
                    print(f"      source {model.nodes.get(s, '?')} {s}")
    if not found:
        print("  no capability-proposal adds or changes it")
    return 0
