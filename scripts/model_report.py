"""decisions, parse, lexicon and logic of scripts/model: the generated index of spec/decisions/ and the requirement
language's tools (the GF conversion's design §15). `model why` went with the capability-proposals it traced (plan 9,
D16)."""

import os
from pathlib import Path

import model_decisions
from model_parse import DECISIONS, as_list, decision_files, frontmatter


def render_decisions(root):
    from model_facts import Model
    index = Model(root)
    index.read_index()
    rows = []
    for path in decision_files(root):
        data, _ = frontmatter(path.read_text())
        if not data.get("id"):
            continue
        rows.append((path.name, data))
    lines = ["# Decisions", "",
             "Generated by `scripts/model decisions` from `spec/decisions/`; never edited by hand.",
             "Each decision's `## Decision` section is standing; the rest of its file is record.", "",
             "| decision | summary | status | tier | supersedes | revisit when |",
             "|---|---|---|---|---|---|"]
    for name, d in rows:
        sup = ", ".join(index.qualify(s, "design-decision") for s in as_list(d.get("supersedes"))) or ""
        rev = d.get("revisit_when") or ""
        cell = lambda s: str(s).replace("|", "\\|")
        lines.append(f"| [{d['id']}]({name}) | {cell(d.get('summary', ''))} | "
                     f"{d.get('status', '')} | {d.get('tier') or ''} | {cell(sup)} | {cell(rev)} |")
    return "\n".join(lines) + "\n"


def cmd_decisions(args):
    text = render_decisions(args.root)
    target = Path(args.root) / DECISIONS / "index.md"
    if args.check:
        current = target.read_text() if target.exists() else ""
        stale = current != text
        print("spec/decisions/index.md is not what `model decisions` writes: run it" if stale
              else "spec/decisions/index.md is current")
        lines, held = model_decisions.report(model_decisions.check_tests(args.root))   # decision-tiers r4, r5
        print("\n".join(lines))
        return 1 if stale or not held else 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    print(f"wrote {target.relative_to(args.root) if not os.path.isabs(args.root) else target}")
    return 0


def _statements(path):
    """A codified-2 file's statements with their line numbers (spec_read); any other file's non-blank lines that are
    not `#` comments (a corpus file's)."""
    import spec_read
    if not spec_read.codified(path, (spec_read.MARKER4,)):
        return [(n, line) for n, line in enumerate(path.read_text().splitlines(), 1)
                if line.strip() and not line.startswith("#")]
    if path.name == "universal.md":
        return [(u.line_no, u.text) for u in spec_read.read_universal(path.parent.parent).conditions]
    return [(r.line_no, r.text) for g in spec_read.capability(path, (spec_read.MARKER4,)).groups for r in g.requirements]


def _requirements(path):
    """{line number: `<capability>#r<n>`} of a codified-2 capability file's requirements; {} for any other file."""
    import spec_read
    if path.parent.name != "capabilities" or not spec_read.codified(path, (spec_read.MARKER4,)):
        return {}
    groups = spec_read.capability(path, (spec_read.MARKER4,)).groups
    return {r.line_no: f"{path.stem}#{r.id}" for g in groups for r in g.requirements}


def cmd_parse(args):
    """`model parse` in grammar 4 (CNL 4's I7a): each line's tree, or its refusal with the longest prefix that parsed,
    the nearest lexicon words and the terms that may follow; a refused requirement of a capability file named
    `<capability>#r<n>` (I9); a line that parses and that a reading rule refuses (spec_lf_read, I11b) printed with its
    refusal and its tree. A context whose `spec/index.md` does not say `language: codified-2` is refused, naming
    `migrate upgrade`."""
    import spec_gf
    import spec_grammar4
    import spec_language
    if not spec_grammar4.marked(args.root):
        print("model parse reads grammar 4: spec/index.md does not say `language: codified-2`; run `migrate upgrade`")
        return 2
    lines = _statements(Path(args.file)) if args.file else [(None, args.line)]
    refused, named = 0, _requirements(Path(args.file)) if args.file else {}
    for n, line in lines:
        head = f"{n}: " if n is not None else ""
        try:
            p = spec_language.parse(args.root, line)
        except (ImportError, spec_gf.GrammarError) as err:
            print(f"grammar 4 could not be built: {err}")
            return 2
        if p.tree is not None:
            print(head + (_form(args.root, p.tree) if args.form else p.tree))
            continue
        refused += 1
        print(head + (f"{named[n]}: " if n in named else "") + p.refusal)
        for tree in p.trees:
            print("  tree: " + tree)
        if not p.trees:
            h = spec_language.hint(args.root, line)
            print(f"  parsed up to: {h['prefix']}")
            print(f"  nearest words: {', '.join(h['near']) or '(none)'}")
            print(f"  may follow: {', '.join(h['follow']) or '(none)'}")
    return 1 if refused else 0


def _form(root, tree):
    """The logical form of a grammar 4 tree, as spec_lf shows it."""
    import spec_grammar4
    import spec_lf
    vocab, _ = spec_grammar4.load(root)
    return spec_lf.show(spec_lf.form(vocab, tree))


def cmd_lexicon(args):
    """The terms by category, an imported pack's marked with its layer and a redefining entry with the pack it
    redefines; with --check, the lexicon's problems and the packs' (v_t16, v_t17) as a report, exit 1 when there is any."""
    import spec_lexicon
    import spec_packs
    import spec_rgl_vocab
    lexicon = spec_lexicon.read(args.root)
    if args.check:
        found = sorted(spec_lexicon.problems(lexicon, spec_rgl_vocab.outer(args.root)) + spec_packs.problems(args.root, lexicon))
        for code, term, message in found:
            print(f"{code}  {term}  {message}")
        print(f"{len(lexicon.terms)} terms, {len(found)} problems")
        return 1 if found else 0
    layered = spec_packs.layers(args.root, lexicon)     # an imported pack's terms first, each shown with its layer
    for cat in spec_lexicon.CATEGORIES + ("",):
        terms = [(layer, t) for layer, t in layered
                 if t.category == cat or (not cat and t.category not in spec_lexicon.CATEGORIES)]
        if terms:
            print(f"{cat or 'no category'} ({len(terms)})")
        for layer, t in terms:
            kinds = dict(t.value_kinds)     # a value's kind, b257: `idea` (noun)
            values = ", ".join(v + (f" ({kinds[v]})" if v in kinds else "") for v in t.values)
            more = {"attribute": f" (of {', '.join(t.kinds)}): {values}",
                    "condition": f" (of {', '.join(t.kinds)})", "relation": f" ({' → '.join(t.kinds)})",
                    "resource": f" ({t.resource})" if t.resource else ""}.get(t.category, "")
            marks = ([layer] if layer.startswith("pack ") else []) + [f"redefines {p}" for p in spec_packs.redefines(t)]
            print(f"  {t.term}{more}" + (f"  [{'; '.join(marks)}]" if marks else ""))
    return 0


def cmd_logic(args):
    """The temporal check: spec_solve's findings and its report."""
    try:
        import spec_solve
    except ImportError:
        print("model logic needs scripts/spec_solve.py (the logic check), which this plugin lacks")
        return 2
    findings = spec_solve.run(args.root, capability=args.capability)
    text, code = spec_solve.report(findings, args.json)
    print(text, end="" if text.endswith("\n") else "\n")
    return code
